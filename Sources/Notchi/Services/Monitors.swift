/// Watches the clipboard and sends new text to the backend's clipboard history.
///
/// Skips anything a password manager marks as concealed or transient (the nspasteboard.org
/// convention 1Password, Bitwarden, Keychain Access… follow), and the backend refuses
/// anything that looks like a password or key, so secrets are never stored.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    /// Our own writes (copying a clip back) are not new clips.
    private var ownChange: Int?

    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in self?.check() }
    }

    /// Puts text on the clipboard without recording it again. A secret is marked concealed (so
    /// clipboard managers and Universal Clipboard skip it) and cleared after a minute.
    func copy(_ text: String, secret: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if secret {
            pb.declareTypes([.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")], owner: nil)
            pb.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        }
        pb.setString(text, forType: .string)
        ownChange = pb.changeCount
        lastChange = pb.changeCount
        if secret {
            let change = pb.changeCount
            DispatchQueue.main.asyncAfter(deadline: .now() + 60) {
                if NSPasteboard.general.changeCount == change { NSPasteboard.general.clearContents() }
            }
        }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard pb.changeCount != ownChange, AppSettings.shared.recordClipboard, Backend.shared.connected else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes),
              let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf16.count <= 20_000 else { return }
        Backend.shared.addClip(text, source: NSWorkspace.shared.frontmostApplication?.localizedName)
    }
}

/// Records which app is in front, as spans, for the Activity page and Workspaces.
///
/// A span ends when you switch apps, go idle for 2 minutes, lock the screen or sleep, and the
/// current one is cut every minute so the numbers stay fresh. Only the app's name and bundle
/// id are recorded, never window titles or content.
final class ActivityMonitor {
    static let shared = ActivityMonitor()

    private var current: (id: String, name: String, start: Date)?
    /// Finished spans not yet sent. A span is only sent once we know you didn't walk away during
    /// it (there has been input since it ended); going idle trims it back to the last input.
    private var pending: [(id: String, name: String, start: Date, end: Date)] = []
    private static let savedKey = "pendingScreenTime"
    private var timer: Timer?
    private var paused = false
    private var idle = false
    private var sending = false
    private static let ignored: Set<String> = ["com.apple.loginwindow", "com.apple.ScreenSaver.Engine"]

    func start() {
        let nc = NSWorkspace.shared.notificationCenter
        nc.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] n in
            let app = n.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            self?.switchTo(app)
        }
        for name in [NSWorkspace.willSleepNotification, NSWorkspace.screensDidSleepNotification,
                     NSWorkspace.sessionDidResignActiveNotification] {
            nc.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in self?.pause(true) }
        }
        for name in [NSWorkspace.didWakeNotification, NSWorkspace.screensDidWakeNotification,
                     NSWorkspace.sessionDidBecomeActiveNotification] {
            nc.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in self?.pause(false) }
        }
        // Locking the screen (⌃⌘Q) doesn't always end the session; listen for it directly.
        let dnc = DistributedNotificationCenter.default()
        dnc.addObserver(forName: NSNotification.Name("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in
            self?.pause(true)
        }
        dnc.addObserver(forName: NSNotification.Name("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in
            self?.pause(false)
        }
        restore()
        switchTo(NSWorkspace.shared.frontmostApplication)
        timer = Timer.scheduledTimer(withTimeInterval: 30, repeats: true) { [weak self] _ in self?.tick() }
    }

    /// On quit: close the running span and keep everything unsent for the next launch.
    func saveForLater() {
        close(at: Date())
        let list: [[String: Any]] = pending.map {
            ["app": $0.id, "name": $0.name, "start": $0.start.timeIntervalSince1970, "end": $0.end.timeIntervalSince1970]
        }
        UserDefaults.standard.set(list, forKey: Self.savedKey)
    }

    private func restore() {
        guard let list = UserDefaults.standard.array(forKey: Self.savedKey) as? [[String: Any]] else { return }
        UserDefaults.standard.removeObject(forKey: Self.savedKey)
        for d in list {
            guard let id = d["app"] as? String, let name = d["name"] as? String,
                  let s = d["start"] as? Double, let e = d["end"] as? Double, e > s else { continue }
            pending.append((id, name, Date(timeIntervalSince1970: s), Date(timeIntervalSince1970: e)))
        }
    }

    /// Seconds since the last keyboard, mouse or trackpad input.
    private var idleSeconds: Double {
        let types: [CGEventType] = [.mouseMoved, .keyDown, .leftMouseDown, .rightMouseDown, .scrollWheel, .flagsChanged]
        return types.map { CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: $0) }.min() ?? 0
    }

    private func switchTo(_ app: NSRunningApplication?) {
        let now = Date()
        close(at: now)
        idle = false            // switching apps means someone is here
        guard !paused, !idle, AppSettings.shared.trackScreenTime, let app, let id = app.bundleIdentifier,
              !Self.ignored.contains(id) else { return }
        current = (id, app.localizedName ?? id, now)
    }

    private func pause(_ on: Bool) {
        if on {
            close(at: Date())
            paused = true
        } else {
            paused = false
            idle = false
            switchTo(NSWorkspace.shared.frontmostApplication)
        }
        flush()
    }

    private func tick() {
        let idleFor = idleSeconds
        let lastInput = Date().addingTimeInterval(-idleFor)
        if !idle, idleFor >= 120 {
            // You walked away: nothing since the last input counts, including spans cut since then.
            close(at: lastInput)
            trimPending(to: lastInput)
            idle = true
        } else if idle, idleFor < 30 {
            idle = false
            switchTo(NSWorkspace.shared.frontmostApplication)
        } else if let c = current, Date().timeIntervalSince(c.start) >= 55 {
            // Cut the running span so the Activity page is never more than a minute behind.
            let app = NSRunningApplication.runningApplications(withBundleIdentifier: c.id).first
            close(at: Date())
            if let app { current = (c.id, app.localizedName ?? c.name, Date()) }
        } else if current == nil, !paused, !idle {
            switchTo(NSWorkspace.shared.frontmostApplication)
        }
        flush()
    }

    private func close(at end: Date) {
        guard let c = current else { return }
        current = nil
        guard end.timeIntervalSince(c.start) >= 1, AppSettings.shared.trackScreenTime else { return }
        // The backend allows 120 UTF-16 units for a name; Swift's prefix counts characters.
        var name = c.name
        while name.utf16.count > 120 { name.removeLast() }
        pending.append((c.id, name, c.start, end))
        if pending.count > 2_000 { pending.removeFirst(pending.count - 2_000) }
    }

    private func trimPending(to cutoff: Date) {
        pending = pending.compactMap { p in
            if p.start >= cutoff { return nil }
            return p.end > cutoff ? (p.id, p.name, p.start, cutoff) : p
        }
    }

    /// Sends finished spans, oldest first, once there has been input after they ended; keeps
    /// them if the backend isn't there yet or can't take them right now.
    private func flush() {
        guard !sending, !pending.isEmpty, Backend.shared.connected else { return }
        let lastInput = Date().addingTimeInterval(-idleSeconds)
        let ready = pending.prefix { $0.end <= lastInput.addingTimeInterval(1) || paused }
        guard !ready.isEmpty else { return }
        let batch = Array(ready.prefix(500))
        let payload: [[String: Any]] = batch.map {
            ["app": $0.id, "name": $0.name, "start": Int64($0.start.timeIntervalSince1970 * 1000),
             "end": Int64($0.end.timeIntervalSince1970 * 1000)]
        }
        sending = true
        Backend.shared.sendSpans(payload) { [weak self] sent in
            guard let self else { return }
            self.sending = false
            guard sent else { return }
            // Drop exactly the spans we sent (the list may have been trimmed meanwhile).
            for b in batch {
                if let i = self.pending.firstIndex(where: { $0.id == b.id && $0.start == b.start }) {
                    self.pending.remove(at: i)
                }
            }
        }
    }
}

/// Starts the backend bundled inside Notchi.app (Contents/Resources/notchi-backend.jar) when
/// it isn't already running, using Java 21 or newer if this Mac has it. Stops it on quit.
enum BackendLauncher {
    private static var process: Process?
    private static var lastAttempt = Date.distantPast
    private static var javaMissing = false

    static var bundledJar: URL? { Bundle.main.url(forResource: "notchi-backend", withExtension: "jar") }

    static func launchIfNeeded() {
        // Look for Java again only every 10 minutes once it wasn't found.
        let wait: TimeInterval = javaMissing ? 600 : 60
        guard AppSettings.shared.useBackend, AppSettings.shared.autoStartBackend,
              process?.isRunning != true, Date().timeIntervalSince(lastAttempt) > wait,
              let jar = bundledJar else { return }
        lastAttempt = Date()
        DispatchQueue.global(qos: .utility).async {
            guard let java = findJava() else {
                DispatchQueue.main.async {
                    javaMissing = true
                    Backend.shared.problem = "Notes, Clipboard and Activity need Java 21 or newer (adoptium.net)."
                }
                return
            }
            let p = Process()
            p.executableURL = java
            p.arguments = ["-Xmx256m", "-jar", jar.path]
            var env = ProcessInfo.processInfo.environment
            env["NOTCHI_TOKEN"] = Backend.token
            p.environment = env
            let log = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Logs/Notchi-backend.log")
            if !FileManager.default.fileExists(atPath: log.path) {
                FileManager.default.createFile(atPath: log.path, contents: nil)
            }
            if let h = try? FileHandle(forWritingTo: log) {
                h.seekToEndOfFile()
                p.standardOutput = h
                p.standardError = h
            }
            do {
                try p.run()
                DispatchQueue.main.async {
                    process = p
                    javaMissing = false
                    Backend.shared.problem = nil
                }
            } catch {
                DispatchQueue.main.async { Backend.shared.problem = "Couldn't start the backend: \(error.localizedDescription)" }
            }
        }
    }

    /// Stops the backend if Notchi started it.
    static func stop() {
        if process?.isRunning == true { process?.terminate() }
        process = nil
    }

    private static func findJava() -> URL? {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/libexec/java_home")
        p.arguments = ["-v", "21+"]
        let out = Pipe()
        p.standardOutput = out
        p.standardError = Pipe()
        do { try p.run() } catch { return nil }
        p.waitUntilExit()
        guard p.terminationStatus == 0,
              let home = String(data: out.fileHandleForReading.readDataToEndOfFile(), encoding: .utf8)?
                .trimmingCharacters(in: .whitespacesAndNewlines), !home.isEmpty else { return nil }
        let java = URL(fileURLWithPath: home).appendingPathComponent("bin/java")
        return FileManager.default.isExecutableFile(atPath: java.path) ? java : nil
    }
}
